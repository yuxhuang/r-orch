#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReviewResult {
    pub criterion: ReviewCriterion,
    pub passed: bool,
    pub output: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct TaskProof {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub branch: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pr_url: Option<String>,
    /// Required even when empty — a task that succeeded with no file changes
    /// still writes `proof: { files_changed: [] }` (PARITY.md §6.8).
    #[serde(default)]
    pub files_changed: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub test_results: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub agent_summary: Option<String>,
}

/// Field order mirrors the TS `Task` interface, which is the YAML emission
/// order (PARITY.md §6.8).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Task {
    pub id: String,
    pub title: String,
    pub description: String,
    pub status: TaskStatus,
    pub priority: i64,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub assignee: Option<String>,
    #[serde(default)]
    pub labels: Vec<String>,
    #[serde(default)]
    pub depends_on: Vec<String>,
    pub created_at: String,
    pub updated_at: String,
    pub attempts: u32,
    pub max_attempts: u32,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub workspace_mode: Option<WorkspaceMode>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub workspace: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub proof: Option<TaskProof>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub review_criteria: Option<Vec<ReviewCriterion>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub review_results: Option<Vec<ReviewResult>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub scope: Option<Vec<String>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub feedback: Option<String>,
    /// camelCase among snake_case fields. This is the on-disk and `--json` key
    /// name, so it is L0 and cannot be normalized (PARITY.md §14.2).
    #[serde(rename = "goalId", default, skip_serializing_if = "Option::is_none")]
    pub goal_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub attachments: Option<Vec<String>>,
}

impl Task {
    /// True when this task was auto-generated by the orchestrator for an
    /// autonomous agent.
    pub fn is_autonomous(&self) -> bool {
        self.labels.iter().any(|l| l == AUTONOMOUS_LABEL)
    }
}


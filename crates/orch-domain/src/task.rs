//! Task domain model — the unit of work (`src/domain/task.ts`).
//!
//! A task moves through `todo → in_progress → review → done`; see
//! [`crate::transitions`] for the transition table.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TaskStatus {
    Todo,
    InProgress,
    Retrying,
    Review,
    Done,
    Failed,
    Cancelled,
}

impl TaskStatus {
    /// Every variant, in declaration order. Used by the exhaustive transition
    /// table test (V9) and by CLI filter validation.
    pub const ALL: [TaskStatus; 7] = [
        TaskStatus::Todo,
        TaskStatus::InProgress,
        TaskStatus::Retrying,
        TaskStatus::Review,
        TaskStatus::Done,
        TaskStatus::Failed,
        TaskStatus::Cancelled,
    ];

    /// The on-disk / `--json` string form.
    pub fn as_str(&self) -> &'static str {
        match self {
            TaskStatus::Todo => "todo",
            TaskStatus::InProgress => "in_progress",
            TaskStatus::Retrying => "retrying",
            TaskStatus::Review => "review",
            TaskStatus::Done => "done",
            TaskStatus::Failed => "failed",
            TaskStatus::Cancelled => "cancelled",
        }
    }
}

impl std::fmt::Display for TaskStatus {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

impl std::str::FromStr for TaskStatus {
    type Err = ();

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        TaskStatus::ALL
            .into_iter()
            .find(|v| v.as_str() == s)
            .ok_or(())
    }
}

/// Label applied to tasks auto-generated by the orchestrator for autonomous agents.
pub const AUTONOMOUS_LABEL: &str = "autonomous";


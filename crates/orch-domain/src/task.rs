#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn status_strings_round_trip_through_serde_and_from_str() {
        for status in TaskStatus::ALL {
            let json = serde_json::to_string(&status).unwrap();
            assert_eq!(json, format!("\"{}\"", status.as_str()));
            assert_eq!(status.as_str().parse::<TaskStatus>(), Ok(status));
        }
        assert!("nope".parse::<TaskStatus>().is_err());
    }

    #[test]
    fn minimal_task_omits_every_optional_field() {
        // PARITY.md §4.2: the as-created shape.
        let task = Task {
            id: "tsk_k3GVRqg".into(),
            title: "Second task".into(),
            description: String::new(),
            status: TaskStatus::Todo,
            priority: 3,
            assignee: None,
            labels: vec![],
            depends_on: vec![],
            created_at: "2026-10-13T16:37:33.426Z".into(),
            updated_at: "2026-10-13T16:37:33.426Z".into(),
            attempts: 0,
            max_attempts: 3,
            workspace_mode: None,
            workspace: None,
            proof: None,
            review_criteria: None,
            review_results: None,
            scope: None,
            feedback: None,
            goal_id: None,
            attachments: None,
        };

        let json = serde_json::to_string_pretty(&task).unwrap();
        assert_eq!(
            json,
            r#"{
  "id": "tsk_k3GVRqg",
  "title": "Second task",
  "description": "",
  "status": "todo",
  "priority": 3,
  "labels": [],
  "depends_on": [],
  "created_at": "2026-10-13T16:37:33.426Z",
  "updated_at": "2026-10-13T16:37:33.426Z",
  "attempts": 0,
  "max_attempts": 3
}"#
        );
    }

    #[test]
    fn goal_id_serializes_as_camel_case() {
        let json = serde_json::json!({
            "id": "tsk_1", "title": "t", "description": "", "status": "todo", "priority": 3,
            "labels": [], "depends_on": [], "created_at": "x", "updated_at": "x",
            "attempts": 0, "max_attempts": 3, "goalId": "goal_abc",
        });
        let task: Task = serde_json::from_value(json).unwrap();
        assert_eq!(task.goal_id.as_deref(), Some("goal_abc"));
        assert!(
            serde_json::to_string(&task)
                .unwrap()
                .contains(r#""goalId":"goal_abc""#)
        );
    }

    #[test]
    fn proof_keeps_empty_files_changed() {
        let proof = TaskProof::default();
        assert_eq!(
            serde_json::to_string(&proof).unwrap(),
            r#"{"files_changed":[]}"#
        );
    }

    #[test]
    fn is_autonomous_reads_the_label() {
        let json = serde_json::json!({
            "id": "tsk_1", "title": "t", "description": "", "status": "todo", "priority": 3,
            "labels": ["autonomous"], "depends_on": [], "created_at": "x", "updated_at": "x",
            "attempts": 0, "max_attempts": 3,
        });
        let task: Task = serde_json::from_value(json).unwrap();
        assert!(task.is_autonomous());
    }
}
